<?php
declare(strict_types=1);
require dirname(__DIR__) . '/vendor/autoload.php';
use SimpleStore\Admin\{AccountManagementRepository, AdminUserRepository, AdminAuth};
use SimpleStore\Auth\PasswordResetService;
use SimpleStore\Customer\{CustomerRepository, CustomerAuth};
use SimpleStore\Database\{ConnectionFactory, SchemaUpdater};

$config = ['host'=>'127.0.0.1','user'=>'root','password'=>(string)getenv('MYSQL_TEST_PASSWORD'),'database'=>'simple_store','port'=>3306];
$server = ConnectionFactory::create($config);
$name = 'shop_users_test_' . bin2hex(random_bytes(4));
$server->query('CREATE DATABASE `' . $name . '` CHARACTER SET utf8mb4 COLLATE utf8mb4_unicode_ci');
$assert = static function (bool $ok, string $message): void { if (!$ok) throw new RuntimeException($message); };
$reject = static function (callable $fn): void {
    try { $fn(); } catch (InvalidArgumentException) { return; }
    throw new RuntimeException('An invalid account mutation was accepted.');
};
try {
    $db = ConnectionFactory::create(array_replace($config, ['database'=>$name]));
    $schema = new SchemaUpdater($db, dirname(__DIR__).'/database/schema.sql'); $schema->apply();
    $users = new AdminUserRepository($db); $manager = new AccountManagementRepository($db);
    $users->createAdmin('owner', password_hash('owner-password', PASSWORD_DEFAULT));
    $owner = (int)$db->insertId();
    $db->query('UPDATE shop_users SET email=%s WHERE id=%i', 'obsolete@example.test', $owner);
    $db->insert('shop_mail_settings', ['id'=>1, 'settings_json'=>json_encode(['admin_recovery_email'=>'owner@example.test', 'from_email'=>'shop@example.test', 'public_base_url'=>'https://example.test'], JSON_THROW_ON_ERROR)]);
    $assert($users->findAdminByEmail('owner@example.test')['id'] == $owner, 'Legacy owner email stopped working.');
    $profile = static fn(string $username, string $role='customer'): array => ['username'=>$username, 'email'=>$username.'@example.test','display_name'=>'Test '.$username,'phone'=>'','role'=>$role,'is_active'=>'1'];
    $rev = static fn(int $id): string => $manager->find($id)['revision'];
    $asForm = static function (int $id, array $changes=[]) use ($manager): array {
        $row = $manager->find($id); $row['is_active']=(string)$row['is_active']; return array_replace($row, $changes);
    };
    $reject(fn()=>$manager->create(999, $profile('intruder','admin'), 'secure-password'));
    $reject(fn()=>$manager->create($owner, $profile('owner'), 'secure-password'));
    $assert($users->findAdminByEmail('obsolete@example.test')===null && $manager->find($owner)['login_email']==='owner@example.test', 'Old stored email displaced the configured legacy identity.');
    $reject(fn()=>$manager->create($owner, array_replace($profile('claim'), ['email'=>'owner@example.test']), 'secure-password'));
    $manager->setPassword($owner, $owner, $rev($owner), 'owner-password');
    $assert($manager->find($owner)['email']==='owner@example.test', 'Legacy manual reset did not retain the effective login email.');
    $second = $manager->create($owner, $profile('second','admin'), 'second-password');
    $customer = $manager->create($owner, array_replace($profile('customer'), ['username'=>'']), 'customer-password');
    $assert(count($manager->page('', '', '', 0)['items'])===3 && count($manager->page('', 'admin', '1', 0)['items'])===2, 'Role filters failed.');
    $assert($manager->page('second', '', '', 0)['items'][0]['id']==$second && $manager->page('', '', '', 0, 1)['nextOffset']===1, 'Search or pagination failed.');
    $assert(!isset($manager->find($second)['password_hash']), 'Password hash exposed by account manager.');
    $reject(fn()=>$manager->create($customer, $profile('intruder','admin'), 'secure-password'));
    $reject(fn()=>$manager->delete($owner, $owner, $rev($owner)));
    $reject(fn()=>$manager->update($owner, $owner, $rev($owner), $profile('owner','customer')));
    $reject(fn()=>$manager->update($owner, $owner, $rev($owner), array_replace($profile('owner','admin'), ['is_active'=>'0'])));
    $manager->update($owner, $owner, $rev($owner), $profile('owner','admin'));
    $assert($users->findAdminByEmail('owner@example.test')['id']==$owner, 'Saving original owner lost login.');
    $auth = new AdminAuth($users, '/test/');
    $assert($auth->signIn('second@example.test', 'second-password') && (int)$auth->user()['id']===$second, 'Second administrator cannot sign in.');
    $oldSession = $_SESSION;
    $assert(!$auth->signIn('owner@example.test', 'second-password'), 'Password accepted for another admin.');
    $manager->update($owner, $second, $rev($second), $asForm($second, ['is_active'=>'0']));
    $assert(!$auth->signedIn(), 'Blocked admin retained session.');
    $reject(fn()=>$manager->setPassword($second, $owner, $rev($owner), 'attacker-password'));
    $manager->update($owner, $second, $rev($second), $asForm($second, ['is_active'=>'1']));
    $_SESSION=$oldSession; $assert(!$auth->signedIn(), 'Reactivation resurrected a revoked session.');
    $assert($auth->signIn('second@example.test', 'second-password'), 'Reactivated admin cannot sign in.');
    $oldSession=$_SESSION;
    $manager->update($owner, $second, $rev($second), $asForm($second, ['role'=>'customer']));
    $manager->update($owner, $second, $rev($second), $asForm($second, ['role'=>'admin']));
    $_SESSION=$oldSession; $assert(!$auth->signedIn(), 'Re-promoting admin resurrected old privileges.');
    $stale=$rev($second);
    $manager->update($owner,$second,$stale,$asForm($second,['display_name'=>'Changed name','phone'=>'+420 123']));
    $reject(fn()=>$manager->update($owner,$second,$stale,$asForm($second,['display_name'=>'Stale overwrite'])));
    $reject(fn()=>$manager->delete($owner,$second,$stale));
    $reject(fn()=>$manager->update($owner,$second,$rev($second),$asForm($second,['email'=>'owner@example.test'])));
    $messages=[];
    $reset = new PasswordResetService($db, static function(string $email,string $subject,string $body) use (&$messages): bool { $messages[]=[$email,$body]; return true; });
    $reset->request('admin','second@example.test','admin.php');
    $assert(count($messages)===1 && $messages[0][0]==='second@example.test', 'Recovery was sent to a different administrator.');
    preg_match('/token=([a-f0-9]{64})/', $messages[0][1], $match);
    $assert($reset->valid('admin',$match[1]), 'Admin recovery token invalid.');
    $auth->signOut(); $auth->signIn('second@example.test','second-password');
    $manager->setPassword($owner,$second,$rev($second),'manually-reset-password');
    $assert(!$auth->signedIn() && !$reset->valid('admin',$match[1]) && !$auth->signIn('second@example.test','second-password') && $auth->signIn('second@example.test','manually-reset-password'), 'Manual reset did not revoke sessions, tokens or old password.');
    $reset->request('admin','unknown@example.test','admin.php');
    $assert(count($messages)===1,'Unknown administrator got reset mail.');
    $address=['label'=>'Doma','recipient'=>'Eva','company'=>'Firma','street'=>'Ulice 1','city'=>'Praha','postal_code'=>'11000','country'=>'CZ','phone'=>'+420 777'];
    $manager->saveAddress($owner,$customer,$rev($customer),null,$address);
    $addressId=(int)$manager->addresses($customer)[0]['id'];
    $reject(fn()=>$manager->saveAddress($owner,$second,$rev($second),$addressId,$address));
    $reject(fn()=>$manager->deleteAddress($owner,$second,$rev($second),$addressId));
    $manager->saveAddress($owner,$customer,$rev($customer),$addressId,array_replace($address,['city'=>'Brno']));
    $assert($manager->addresses($customer)[0]['city']==='Brno','Address edit failed.');
    $db->insert('shop_orders',['user_id'=>$customer,'order_number'=>'ACCOUNT-1','status'=>'new','total_czk'=>1800,'items_json'=>'[{"name":"Boty"}]','shipping_json'=>'{"city":"Praha"}']);
    $orderId=(int)$db->insertId();
    $db->insert('shop_invoices',['order_id'=>$orderId,'order_number'=>'ACCOUNT-1','document_number'=>'INVOICE-1','issue_date'=>'2026-10-24','due_date'=>'2026-10-31','seller_json'=>'{}','buyer_json'=>'{"name":"Eva"}','items_json'=>'[]','subtotal_czk'=>1800,'shipping_czk'=>0,'total_czk'=>1800]);
    $invoiceBefore=$db->queryFirstRow('SELECT * FROM shop_invoices WHERE order_id=%i',$orderId);
    $db->insert('shop_after_sales_cases',['user_id'=>$customer,'order_id'=>$orderId,'case_number'=>'CASE-1','case_token'=>str_repeat('a',64),'request_key'=>str_repeat('b',64),'order_number'=>'ACCOUNT-1','customer_email'=>'customer@example.test','customer_name'=>'Eva','order_total_czk'=>1800,'kind'=>'complaint','item_name'=>'Boty','item_line'=>0,'quantity'=>1,'unit_price_czk'=>1800,'description'=>'Test','requested_solution'=>'repair']);
    $auth->signOut(); session_write_close();
    $customerAuth = new CustomerAuth(new CustomerRepository($db), '/test/');
    $assert($customerAuth->signIn('customer@example.test','customer-password'),'Customer login broken.');
    $manager->delete($owner,$customer,$rev($customer));
    $assert(!$customerAuth->signedIn() && $manager->find($customer)===null && $manager->addresses($customer)===[], 'Deleted customer retained account data or session.');
    $order=$db->queryFirstRow('SELECT * FROM shop_orders WHERE id=%i',$orderId);
    $assert($order['user_id']===null && $order['total_czk']==1800 && $order['shipping_json']==='{"city":"Praha"}', 'Account deletion changed order snapshots.');
    $assert($db->queryFirstRow('SELECT * FROM shop_invoices WHERE order_id=%i',$orderId)===$invoiceBefore, 'Account deletion changed the invoice.');
    $assert($db->queryFirstRow('SELECT * FROM shop_after_sales_cases WHERE order_id=%i',$orderId)['user_id']===null, 'Claim still linked to deleted user.');
    $manager->delete($owner,$second,$rev($second));
    $reject(fn()=>$manager->delete($owner,$owner,$rev($owner)));
    $assert($users->hasAdmin(), 'Last administrator disappeared.');
    // Old-schema login must remain usable so the owner can run the new migration.
    $customerAuth->signOut(); session_write_close();
    $db->query('ALTER TABLE shop_users DROP COLUMN auth_version');
    $assert(!$manager->installed(),'Management writes allowed without session migration.');
    $auth = new AdminAuth($users,'/test/');
    $assert($auth->signIn('owner@example.test','owner-password'),'Owner locked out before migration.');
    $db->query('DELETE FROM shop_schema_updates'); $schema->apply();
    $assert($manager->installed() && $auth->signedIn(),'Migration lost owner access.');
    $schema->apply();
    echo "Administrator/customer management database checks passed.\n";
} finally {
    $server->query('DROP DATABASE `' . $name . '`');
}
